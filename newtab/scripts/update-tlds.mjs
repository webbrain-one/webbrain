// Regenerates src/features/agent/tlds.js from IANA's list of top-level domains,
// which the new tab uses to tell an address ("example.com") from a prompt that
// only looks like one ("node.js"). Run: npm run update:tlds
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt';
const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/features/agent/tlds.js');

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE}: HTTP ${response.status}`);
const text = await response.text();
const version = /^#\s*Version\s+(\d+)/m.exec(text)?.[1];
const tlds = text.split('\n').map((line) => line.trim().toLowerCase()).filter((line) => line && !line.startsWith('#'));
if (!version || tlds.length < 1000 || tlds.some((tld) => !/^(?:[a-z]{2,63}|xn--[a-z0-9-]+)$/.test(tld))) {
  throw new Error(`${SOURCE}: unexpected contents (version ${version}, ${tlds.length} entries)`);
}

const lines = [];
for (let i = 0; i < tlds.length; i += 12) lines.push(tlds.slice(i, i + 12).join(' '));
writeFileSync(OUT, `// Generated by newtab/scripts/update-tlds.mjs from ${SOURCE}
// (version ${version}). Do not edit by hand: run \`npm run update:tlds\` in newtab/.
// Lower-case ASCII, internationalized TLDs in punycode, as URL#hostname gives them.
export const TLDS_VERSION = '${version}';

export const TLDS = new Set(\`
${lines.join('\n')}
\`.trim().split(/\\s+/));
`);
console.log(`Wrote ${tlds.length} TLDs (version ${version}) to ${path.relative(process.cwd(), OUT)}`);
